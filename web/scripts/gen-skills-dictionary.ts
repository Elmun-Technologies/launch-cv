/**
 * Writes src/lib/skills-dictionary.ts from the `keywords` of every resume example, so the
 * editor's keyword panel can match job descriptions without shipping the full examples
 * (about 600 KB of page text) to the browser.
 *
 * Run after adding or changing example keywords:  npx tsx scripts/gen-skills-dictionary.ts
 * `npx tsx src/lib/resume-score.check.ts` fails when the file is out of date.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSkillsDictionary } from "../src/lib/skills-dictionary-source";

const entries = buildSkillsDictionary();
const lines = entries.map(([term, kind]) => `  [${JSON.stringify(term)}, ${JSON.stringify(kind)}],`);
const out = `/**
 * Skills dictionary for the editor's keyword panel: every keyword from the resume examples
 * (lib/resume-examples*.ts), with its kind from each example's \`keywordSort\`.
 *
 * GENERATED by scripts/gen-skills-dictionary.ts. Do not edit by hand.
 */
import type { SkillKind } from "@/lib/skills-dictionary-source";

export const SKILLS_DICTIONARY: ReadonlyArray<readonly [term: string, kind: SkillKind]> = [
${lines.join("\n")}
];
`;
writeFileSync(join(__dirname, "../src/lib/skills-dictionary.ts"), out);
console.log(`skills-dictionary: wrote ${entries.length} terms`);
