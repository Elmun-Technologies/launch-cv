/** Unique verbs on the page (a verb listed in two groups counts once). */
export function countVerbs(groups: VerbGroup[] = VERB_GROUPS): number {
  return new Set(groups.flatMap((g) => g.verbs.map((v) => v.verb.toLowerCase()))).size;
}

